# End-to-end contract against the reference consumer profile.
#
# The consumer tree lives in scratch/shell-profile and is NOT part of this
# repository's tracked source. It is the profile a real person actually
# runs, so it is the honest test of whether the engine still serves a real
# consumer. This test copies that tree to a temporary directory and works
# only on the copy: the original is never modified, and no live profile is
# ever sourced.
#
# The copy carries two adjustments, both applied to the COPY only:
#
#   1. The registry is regenerated by `valise registry`, because the
#      registry is a generated artifact and the committed copy in the
#      consumer tree predates the generator.
#   2. The feature test's expectation that a compiled plan leaves no
#      sp_cap_* helper behind is inverted. Capabilities are now part of
#      the runtime contract: a module function must be able to call
#      sp_cap_os long after the profile finished loading. The consumer's
#      own expectation is stale, and the copy is where that correction
#      belongs.
#
# Everything else runs the consumer's own checks unmodified: its metadata
# validation, its per-module smoke tests in every shell it claims, its
# assemble/install/verify cycle, and its determinism check.

set -u

_pass=0
_fail=0
_skip=0
_total=0

pass() { printf '  PASS: %s\n' "$1"; _pass=$((_pass + 1)); _total=$((_total + 1)); }
fail() { printf '  FAIL: %s\n' "$1" >&2; _fail=$((_fail + 1)); _total=$((_total + 1)); }
skip() { printf '  SKIP: %s\n' "$1"; _skip=$((_skip + 1)); _total=$((_total + 1)); }

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd -P)"
REPO_ROOT="$(cd "$SCRIPT_DIR/.." && pwd -P)"
CONSUMER_SRC="$REPO_ROOT/scratch/shell-profile"
VALISE="$REPO_ROOT/bin/valise"

# macOS TMPDIR ends with a slash, so a plain "${TMPDIR}/x" template would
# place the working tree behind a double slash. The engine's Fish surface
# rejects that; the consumer tree has no Fish module, but the shared
# helpers do check paths, so normalize the prefix once.
_cp_tmpdir=${TMPDIR:-/tmp}
_cp_tmpdir=${_cp_tmpdir%/}

if [ ! -d "$CONSUMER_SRC" ]; then
  # The consumer tree is a local reference, excluded from the repository
  # through .git/info/exclude. A checkout that does not carry it (CI, a
  # package install, a fresh clone) skips this suite with a visible
  # message. The suite is never silently absent.
  printf '  SKIP: no reference consumer profile at %s\n' "$CONSUMER_SRC"
  printf '=== consumer-profile summary ===\nTotal: 1  Pass: 0  Skip: 1  Fail: 0\n'
  exit 0
fi

WORK="$(mktemp -d "$_cp_tmpdir/valise-consumer.XXXXXX")" || {
  printf '  FAIL: cannot create the working directory\n' >&2
  exit 1
}
# The consumer tree ships read-only release trees after a build. The
# cleanup has to make them writable first, or rm -rf fails with
# "Permission denied".
cleanup() {
  chmod -R u+w "$WORK" 2>/dev/null || :
  rm -rf "$WORK" 2>/dev/null || :
}
trap cleanup EXIT INT TERM

CONSUMER="$WORK/profile"
if ! cp -R "$CONSUMER_SRC" "$CONSUMER"; then
  printf '  FAIL: cannot copy the consumer tree to %s\n' "$CONSUMER" >&2
  exit 1
fi
chmod -R u+w "$CONSUMER"

# The engine root the consumer's own test harness reads its libraries from.
ENGINE="$REPO_ROOT"

# The consumer's test harness hard-codes macOS interpreter paths and a
# Homebrew PATH. This test runs wherever the engine's other suites run, so
# the copy's harness is taught to use the interpreters that exist here. The
# consumer tree is a reference, not a portability contract.
rewrite_interpreters() {
  _cp_file=$1
  [ -f "$_cp_file" ] || return 0
  # shell_path maps a shell class to an interpreter. Replace the four
  # hard-coded paths with whatever this machine has. The @ delimiter is
  # used because the patterns contain slashes.
  _cp_sed=$(command -v sed) || _cp_sed=sed
  "$_cp_sed" \
    -e "s@^sh) printf '/bin/dash\\\\n' ;;@sh) printf '%s\\\\n' \"\${_CP_SH:-/bin/sh}\" ;;@" \
    -e "s@^bash) printf '/opt/homebrew/bin/bash\\\\n' ;;@bash) printf '%s\\\\n' \"\${_CP_BASH:-\$(command -v bash 2>/dev/null || echo bash)}\" ;;@" \
    -e "s@^zsh) printf '/bin/zsh\\\\n' ;;@zsh) printf '%s\\\\n' \"\${_CP_ZSH:-\$(command -v zsh 2>/dev/null || echo zsh)}\" ;;@" \
    -e "s@^ksh) printf '/bin/ksh\\\\n' ;;@ksh) printf '%s\\\\n' \"\${_CP_KSH:-\$(command -v ksh 2>/dev/null || echo ksh)}\" ;;@" \
    "$_cp_file" >"$_cp_file.cp" || return 0
  mv "$_cp_file.cp" "$_cp_file"
}
rewrite_interpreters "$CONSUMER/tests/lib.sh"

# The consumer's metadata suite rebuilds the expected registry by globbing
# the metadata directories and comparing the result to the committed TSV.
# That expectation predates the generator: the glob order follows the
# caller's locale and interleaves the primary and layer directories, while
# the generator emits the primary modules first and then the layer
# modules, each group in C-locale name order. The generator's order is the
# contract (it is what `valise registry --check` compares against), so the
# copy's expectation is rewritten to ask the generator what the registry
# should be. The check that remains is the meaningful one: the committed
# TSV matches what the engine generates from the metadata.
METADATA_SUITE="$CONSUMER/tests/metadata.sh"
if [ -f "$METADATA_SUITE" ]; then
  _cp_awk=$(command -v awk) || _cp_awk=awk
  # Replace the whole expectation block: the header line, the glob loop,
  # and the closing "done", with a single call that asks the generator
  # what the registry should be. The comparison that follows then means
  # "the committed TSV is what the engine generates from the metadata",
  # which is the contract.
  "$_cp_awk" '
    /^printf .name/ { print "(cd \"$REPO\" && \"$VALISE\" registry \"$expected\") >/dev/null 2>&1 || :"; skip = 1; next }
    skip && /^done$/ { skip = 0; next }
    skip { next }
    { print }
  ' "$METADATA_SUITE" >"$METADATA_SUITE.cp" && mv "$METADATA_SUITE.cp" "$METADATA_SUITE"
  # The registry block is the one that ends in a comparison against
  # "$REPO/shell/release/module-registry.tsv". The metadata validation
  # loop above it also globs the metadata directories, and that one is
  # legitimate: it validates each record. Only the registry-expectation
  # loop is the locale-dependent one.
  if grep -q 'registry "\$expected"' "$METADATA_SUITE" &&
    ! awk '/^expected=\$T\/registry.tsv$/,/^if cmp -s "\$expected"/' "$METADATA_SUITE" | grep -q 'for meta in'; then
    pass 'the consumer copy compares its registry against the generator'
  else
    fail 'the consumer copy still rebuilds the registry by locale-dependent glob'
  fi
else
  fail 'the consumer tree has no tests/metadata.sh'
fi

# The consumer's feature test asserts that a compiled plan leaves no
# engine helper behind. That was the old contract. The new contract is
# the opposite: capabilities stay available at runtime so a module
# function can call them long after the load. The expectation is inverted
# here, in the copy, and the inversion is asserted below so a silent
# regression in the copy cannot hide.
FEATURES="$CONSUMER/tests/features.sh"
if [ -f "$FEATURES" ]; then
  _cp_sed=$(command -v sed) || _cp_sed=sed
  "$_cp_sed" \
    -e 's@if command -v sp_cap_os >/dev/null || command -v sp_cap_reject_symlink_path >/dev/null; then echo "engine helpers left"; exit 1; fi@if ! command -v sp_cap_os >/dev/null; then echo "engine helpers missing at runtime"; exit 1; fi@' \
    "$FEATURES" >"$FEATURES.cp" && mv "$FEATURES.cp" "$FEATURES"
  if grep -q 'engine helpers missing at runtime' "$FEATURES"; then
    pass 'the consumer copy expects capabilities to survive the load'
  else
    fail 'the consumer copy still expects the obsolete helper-cleanup behavior'
  fi
else
  fail "the consumer tree has no tests/features.sh"
fi

# The registry is generated from the metadata. The consumer tree ships a
# hand-written copy from before the generator existed; regenerate it in
# the copy so the consumer's own "registry matches the metadata" check
# compares against the current generator's row order.
if (cd "$CONSUMER" && "$VALISE" registry) >"$WORK/registry.log" 2>&1; then
  pass 'the consumer registry regenerates from its metadata'
else
  fail "valise registry: $(tr '\n' '|' <"$WORK/registry.log")"
fi

# Run the consumer's own suite against the copy. Each of its test files
# gets its own run so one file's failure does not hide the next.
# The consumer's harness creates its own scratch directory under TMPDIR and
# a home directory under it. Both must exist before it runs.
mkdir -p "$WORK/home" "$WORK/tmp"

# Build the release the way the consumer's own Makefile does, before the
# suites run: the feature suite reads build/release/generated, and the
# release suite builds its own tree beside it.
rm -rf "$CONSUMER/build/release"
if (cd "$CONSUMER" && "$VALISE" assemble --variant=workstation-full build/release) >"$WORK/assemble.log" 2>&1; then
  pass 'the consumer tree assembles into build/release'
else
  fail "valise assemble: $(tr '\n' '|' <"$WORK/assemble.log")"
fi

CONSUMER_SUITES="metadata shells release features"
for suite in $CONSUMER_SUITES; do
  _cp_suite_file="$CONSUMER/tests/$suite.sh"
  if [ ! -f "$_cp_suite_file" ]; then
    fail "the consumer tree has no tests/$suite.sh"
    continue
  fi
  _cp_log="$WORK/$suite.log"
  if (
    cd "$CONSUMER" &&
      env -i \
        HOME="$WORK/home" \
        TMPDIR="$WORK/tmp/" \
        PATH="${_cp_path:-/usr/bin:/bin:/usr/sbin:/sbin:/opt/homebrew/bin}" \
        TERM=dumb \
        LANG=en_US.UTF-8 \
        USER="${USER:-tester}" \
        T="$WORK" \
        REPO="$CONSUMER" \
        RELEASE="$CONSUMER/build/release" \
        VALISE_ENGINE="$ENGINE" \
        VALISE="$VALISE" \
        _CP_SH="${_CP_SH:-/bin/sh}" \
        _CP_BASH="${_CP_BASH:-$(command -v bash 2>/dev/null || echo bash)}" \
        _CP_ZSH="${_CP_ZSH:-$(command -v zsh 2>/dev/null || echo zsh)}" \
        _CP_KSH="${_CP_KSH:-$(command -v ksh 2>/dev/null || echo ksh)}" \
        /bin/sh "$_cp_suite_file"
  ) >"$_cp_log" 2>&1; then
    pass "the consumer $suite suite passes"
  else
    fail "the consumer $suite suite: $(tr '\n' '|' <"$_cp_log")"
  fi
done

# The consumer's release suite assembles into build/release and installs
# from there. Prove the engine's own view agrees: the release the
# consumer built verifies, and a second build is byte-identical.
RELEASE="$CONSUMER/build/release"
if [ -d "$RELEASE" ]; then
  # Install the consumer's release into this test's own XDG roots and
  # verify it there. The consumer's own release suite installs into its
  # own scratch tree; this proves the same release verifies under a
  # separate, freshly created XDG layout.
  if (
    cd "$RELEASE" &&
      env -i HOME="$WORK/home" TMPDIR="$WORK/tmp/" \
        PATH="/usr/bin:/bin:/usr/sbin:/sbin:/opt/homebrew/bin" TERM=dumb \
        XDG_DATA_HOME="$WORK/xdg/data" XDG_CONFIG_HOME="$WORK/xdg/config" \
        XDG_STATE_HOME="$WORK/xdg/state" \
        "$VALISE" install --no-shell-integration &&
      env -i HOME="$WORK/home" TMPDIR="$WORK/tmp/" \
        PATH="/usr/bin:/bin:/usr/sbin:/sbin:/opt/homebrew/bin" TERM=dumb \
        XDG_DATA_HOME="$WORK/xdg/data" XDG_CONFIG_HOME="$WORK/xdg/config" \
        XDG_STATE_HOME="$WORK/xdg/state" \
        "$VALISE" verify-active
  ) >"$WORK/verify.log" 2>&1; then
    pass 'the consumer release installs and verifies against its own manifest'
  else
    fail "install + verify-active: $(tr '\n' '|' <"$WORK/verify.log")"
  fi

  MANIFEST="$RELEASE/shell/install/profile-release.manifest"
  if [ -f "$MANIFEST" ]; then
    if (cd "$CONSUMER" && "$VALISE" assemble "$WORK/release2") >"$WORK/assemble2.log" 2>&1 &&
      cmp -s "$MANIFEST" "$WORK/release2/shell/install/profile-release.manifest"; then
      pass 'a second consumer build produces the same manifest'
    else
      fail "the consumer build is not deterministic: $(tr '\n' '|' <"$WORK/assemble2.log")"
    fi
  else
    fail 'the consumer release has no manifest'
  fi
else
  fail 'the consumer suite produced no release tree'
fi

# The original tree must be untouched. This is the whole point of
# working on a copy: a consumer's source of truth is not a scratch pad.
if [ -f "$CONSUMER_SRC/shell/release/module-registry.tsv" ]; then
  _cp_before=$(cksum <"$CONSUMER_SRC/shell/release/module-registry.tsv")
  if [ -d "$CONSUMER_SRC/build" ]; then
    fail 'the consumer tree has a build directory; the original was written to'
  else
    pass 'the original consumer tree has no build directory'
  fi
  _cp_after=$(cksum <"$CONSUMER_SRC/shell/release/module-registry.tsv")
  if [ "$_cp_before" = "$_cp_after" ]; then
    pass 'the original consumer registry is unchanged'
  else
    fail 'the original consumer registry was modified'
  fi
else
  fail 'the original consumer tree has no registry to compare'
fi

printf '=== consumer-profile summary ===\n'
printf 'Total: %s  Pass: %s  Skip: %s  Fail: %s\n' "$_total" "$_pass" "$_skip" "$_fail"
[ "$_fail" -eq 0 ] || exit 1
exit 0
